/** Generated by `check --visual`; ignored by preview's watcher and the `init` .gitignore. */
export const VISUAL_DIRECTORY = '.mapbard-visual';

const cliVersion = (
  JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf8')) as {
    version: string;
  }
).version;

/**
 * `update` rewrites the project's goldens from this run (offline only); `frames` adds the frame
 * sample, which is reported but never gates.
 */
export type VisualOptions = {
  network: NetworkMode;
  failOnWarnings?: boolean;
  update?: boolean;
  frames?: boolean;
};

/**
 * Captures a built publication into `out`; the default drives a real headless Chromium.
 * `noiseRuns` extra runs capture again into `out/noise-<n>/`, so `--update` can measure how much
 * the same build differs from itself.
 */
export type CaptureRunner = (options: {
  publication: string;
  out: string;
  network: NetworkMode;
  noiseRuns?: number;
  frames?: boolean;
}) => Promise<{
  report: CaptureReport;
  contactSheet: string;
  browserVersion?: string;
  noise?: { out: string; captures: Sample[] }[];
  frames?: FrameReport[];
}>;

/**
 * The frame sample runs in its own browser on Chromium's default WebGL path: forced SwiftShader
 * keeps captures identical across machines but is many times slower at desktop size, so its
 * frame times would mostly measure the software rasteriser.
 */
async function sampleFrames(options: { publication: string; network: NetworkMode }) {
  const browser = await launchBrowser(process.env, ['--allow-file-access-from-files']);
  try {
    return await probeStoryFrames(browser, options);
  } finally {
    await browser.close();
  }
}

export const browserCapture: CaptureRunner = async (options) => {
  const browser = await launchBrowser();
  try {
    const report = await captureStory(browser, options);
    const contactSheet = await writeContactSheet(browser, options.out, report.captures);
    const noise: { out: string; captures: Sample[] }[] = [];
    for (let run = 1; run <= (options.noiseRuns ?? 0); run++) {
      const out = join(options.out, `noise-${run}`);
      // The same full run, sweep included: the sweep's path leaves the map in the state the
      // captures show (tile cache, label placement), so a captures-only run differs.
      const again = await captureStory(browser, { ...options, out });
      noise.push({ out, captures: again.captures });
    }
    const frames = options.frames ? await sampleFrames(options) : undefined;
    return {
      report,
      contactSheet,
      browserVersion: browser.version(),
      noise,
      ...(frames ? { frames } : {}),
    };
  } finally {
    await browser.close();
  }
};

/** Diagnostics already reported by the check step are not repeated from the build step. */
const keyOf = (entry: Diagnostic): string =>
  JSON.stringify([entry.code, entry.path, entry.message]);

/**
 * `mapbard check --visual`: the normal check, then (without check errors) a build into
 * `.mapbard-visual/build/`, captures into `.mapbard-visual/captures/` and the findings as
 * diagnostics. Offline runs also compare the captures with the project's goldens, or rewrite
 * them with `update`; nothing else in the project, lockfile included, is changed.
 */
export async function checkVisual(
  root: string,
  options: VisualOptions,
  capture: CaptureRunner = browserCapture,
): Promise<Outcome> {
  const checked = await prepare(root, false, false);
  const checkResult = checked.compiled
    ? { scenes: checked.compiled.scenes.length, requiredNetwork: checked.compiled.requiredNetwork }
    : undefined;
  if (!checked.compiled || checked.diagnostics.some((entry) => entry.severity === 'error'))
    return { result: checkResult, diagnostics: checked.diagnostics };
  const buildDirectory = join(VISUAL_DIRECTORY, 'build');
  const built = await build(root, buildDirectory, options.network === 'offline', {
    refresh: false,
    record: false,
  });
  const seen = new Set(checked.diagnostics.map(keyOf));
  const diagnostics = [
    ...checked.diagnostics,
    ...built.diagnostics.filter((entry) => !seen.has(keyOf(entry))),
  ];
  if (diagnostics.some((entry) => entry.severity === 'error'))
    return { result: checkResult, diagnostics };
  const sizes = (built.result as { sizes?: unknown } | undefined)?.sizes;
  const publication = resolve(root, buildDirectory);
  const out = resolve(root, VISUAL_DIRECTORY, 'captures');
  // Screenshots from an earlier run would otherwise mix with this one.
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  let captured: Awaited<ReturnType<CaptureRunner>>;
  try {
    captured = await capture({
      publication,
      out,
      network: options.network,
      noiseRuns: options.update ? NOISE_RUNS - 1 : 0,
      frames: Boolean(options.frames),
    });
  } catch (error) {
    return {
      result: checkResult,
      diagnostics: [
        ...diagnostics,
        error instanceof BrowserMissingError
          ? issue(
              'VISUAL_BROWSER_MISSING',
              'export',
              [],
              `Visual checks need a headless Chromium. ${error.message}`,
              'Install Google Chrome, run `npx playwright install chromium`, or set MAPBARD_CHROME_PATH to a Chrome or Chromium executable.',
            )
          : issue(
              'VISUAL_RUNTIME',
              'export',
              [],
              `The visual check could not capture the story: ${error instanceof Error ? error.message : String(error)}`,
              `Open ${buildDirectory}/index.html in a browser and fix what stops the story from starting.`,
            ),
      ],
    };
  }
  const sceneIndex = new Map(checked.compiled.scenes.map((scene, index) => [scene.id, index]));
  const visual = visualDiagnostics(captured.report, sceneIndex, options);
  const goldens = await checkGoldens(root, out, captured, sceneIndex, options);
  const reportPath = join(out, 'report.json');
  await writeFile(
    reportPath,
    `${JSON.stringify({ ...captured.report, goldens: goldens.summary, ...(captured.frames ? { frames: captured.frames } : {}) }, null, 2)}\n`,
  );
  const visualAll = [...visual, ...goldens.diagnostics];
  return {
    result: {
      ...checkResult,
      visual: {
        ...visualSummary(captured.report, visualAll),
        build: publication,
        report: reportPath,
        contactSheet: captured.contactSheet,
        goldens: goldens.summary,
        ...(captured.frames ? { frames: captured.frames } : {}),
        ...(sizes ? { sizes } : {}),
      },
    },
    diagnostics: [...diagnostics, ...visualAll],
  };
}

/** Goldens exist only for offline runs: rewrite them with `update`, else compare when present. */
async function checkGoldens(
  root: string,
  out: string,
  captured: Awaited<ReturnType<CaptureRunner>>,
  sceneIndex: ReadonlyMap<string, number>,
  options: VisualOptions,
): Promise<{ summary: Record<string, unknown>; diagnostics: Diagnostic[] }> {
  const directory = join(root, GOLDEN_DIRECTORY);
  if (options.network !== 'offline')
    return {
      summary: { status: 'skipped', reason: 'goldens compare offline runs only' },
      diagnostics: [],
    };
  if (options.update) {
    const noise = await measureNoise([
      { out, captures: captured.report.captures },
      ...(captured.noise ?? []),
    ]);
    // The noise captures served their purpose; only the main run stays in captures/.
    for (const run of captured.noise ?? []) await rm(run.out, { recursive: true, force: true });
    const manifest = await writeGoldens(root, out, captured.report.captures, {
      mapbard: cliVersion,
      chromium: captured.browserVersion ?? 'unknown',
      platform: process.platform,
      viewports: VIEWPORTS,
      noise,
    });
    return {
      summary: {
        status: 'updated',
        directory,
        captures: manifest.captures.length,
        maxDiffRatio: manifest.maxDiffRatio,
        noise: manifest.noise,
      },
      diagnostics: [],
    };
  }
  const manifest = await readGoldenManifest(root);
  if (!manifest) return { summary: { status: 'none', directory }, diagnostics: [] };
  const { comparisons, diagnostics } = await compareGoldens(
    root,
    out,
    captured.report.captures,
    manifest,
    sceneIndex,
  );
  // Goldens from another platform always differ in text, so that warning never gates.
  const failOnWarnings = (entry: Diagnostic): Diagnostic =>
    options.failOnWarnings && manifest.platform === process.platform
      ? { ...entry, severity: 'error' }
      : entry;
  return {
    summary: {
      status: diagnostics.length ? 'mismatch' : 'match',
      directory,
      platform: manifest.platform,
      maxDiffRatio: manifest.maxDiffRatio,
      compared: comparisons.length,
      mismatched: comparisons.filter((entry) => entry.status !== 'match').length,
      worstRatio: Math.max(0, ...comparisons.map((entry) => entry.ratio ?? 0)),
    },
    diagnostics: diagnostics.map(failOnWarnings),
  };
}
