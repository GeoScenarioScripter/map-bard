/**
 * Emits `bundle-data.js`, which assigns the narrative and the raw geo data to a
 * global the runtime reads. Data is inlined (not fetched) so the bundle works
 * from `file://` with no server.
 */
import type { GeoNarrative } from '@mapbard/schema';
import type { DataMap, LocalContextMap } from './types.js';

// Characters that can prematurely close a <script> element (`<`, `>`) or are
// invalid raw in JS string literals (U+2028 line sep, U+2029 paragraph sep).
// Built from char codes to keep this source file pure ASCII.
const UNSAFE_IN_SCRIPT = new RegExp('[<>' + String.fromCharCode(0x2028, 0x2029) + ']', 'g');

/** Escape characters that could break out of the `<script>` element or JS. */
function safeJson(value: unknown): string {
  return JSON.stringify(value).replace(
    UNSAFE_IN_SCRIPT,
    (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'),
  );
}

export function buildBundleData(
  narrative: GeoNarrative,
  data: DataMap,
  localContextMap?: LocalContextMap,
): string {
  return `/* Generated by @mapbard/renderer — do not edit. */\nwindow.MAPBARD = ${safeJson({
    narrative,
    data,
    localContextMap,
  })};\n`;
}
