import { createHash } from 'node:crypto';
import {
  CompiledSchema,
  PublicationInputsSchema,
  RenderCompiledOptionsSchema,
  type Compiled,
  type CompiledBundle,
  type Diagnostic,
  type PublicationInputs,
  type RenderCompiledOptions,
  type Result,
} from '@mapbard/schema';
import { FONT_FILES } from './fonts.js';

const unsafeScript = /[<>\u2028\u2029]/g;
const safeJson = (value: unknown): string =>
  JSON.stringify(value).replace(
    unsafeScript,
    (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`,
  );
const escapeHtml = (value: string): string =>
  value.replace(
    /[&<>"']/g,
    (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]!,
  );

function issue(
  code: Diagnostic['code'],
  path: Diagnostic['path'],
  message: string,
  remedy: string,
  ids: Diagnostic['ids'] = {},
): Diagnostic {
  return { code, severity: 'error', artifact: 'export', path, ids, message, remedy };
}

function sha256(bytes: Uint8Array): string {
  return `sha256:${createHash('sha256').update(bytes).digest('hex')}`;
}

function safePath(path: string): boolean {
  return (
    !path.startsWith('/') &&
    !path.includes('\\') &&
    !/^[A-Za-z]:/.test(path) &&
    path.split('/').every((part) => part !== '' && part !== '.' && part !== '..')
  );
}

const FALLBACK_STACKS = {
  serif: "Georgia, 'Times New Roman', serif",
  'sans-serif': "system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
} as const;
const SHADOWS = {
  none: 'none',
  soft: '0 12px 34px rgba(0, 0, 0, 0.14)',
  strong: '0 18px 48px rgba(0, 0, 0, 0.42)',
} as const;

/** Families the publication must ship in `fonts/`. */
export function bundledFonts(compiled: Compiled): string[] {
  const { display, body } = compiled.theme.fonts;
  return [...new Set([display, body].filter((font) => font.bundled).map((font) => font.family))];
}

/** Generated from resolved tokens; the schema already restricts colours and family names. */
export function themeCss(compiled: Compiled): string {
  const { colors, fonts, type, card } = compiled.theme;
  const faces = bundledFonts(compiled).map((family) => {
    const file = FONT_FILES[family];
    if (!file) throw new Error(`No bundled font file for ${family}`);
    return `@font-face{font-family:'${family}';src:url('${file.font[1]}') format('woff2');font-weight:100 900;font-style:normal;font-display:swap}`;
  });
  const stack = (font: Compiled['theme']['fonts']['display']) =>
    `'${font.family}', ${FALLBACK_STACKS[font.fallback]}`;
  const px = (value: number) => `${Math.round(value * 100) / 100}px`;
  const step = (power: number) => px(type.basePx * type.ratio ** power);
  const channels =
    colors.page.length < 7
      ? [1, 2, 3].map((i) => colors.page[i]!.repeat(2))
      : [1, 3, 5].map((i) => colors.page.slice(i, i + 2));
  const dark = channels.reduce((sum, hex) => sum + parseInt(hex, 16), 0) < 384;
  const vars: Record<string, string> = {
    'color-scheme': dark ? 'dark' : 'light',
    '--mb-page': colors.page,
    '--mb-ink': colors.ink,
    '--mb-muted': colors.muted,
    '--mb-accent': colors.accent,
    '--mb-card-bg': colors.card,
    '--mb-rule': colors.rule,
    '--mb-land': colors.land,
    '--mb-display': stack(fonts.display),
    '--mb-body': stack(fonts.body),
    '--mb-text-small': step(-1),
    '--mb-text-base': px(type.basePx),
    '--mb-text-h3': step(1),
    '--mb-text-h2': step(2),
    '--mb-text-h1-min': step(3),
    '--mb-text-h1-max': step(5),
    '--mb-line-height': String(type.lineHeight),
    '--mb-heading-weight': String(type.headingWeight),
    '--mb-card-radius': px(card.radius),
    '--mb-card-blur': px(card.blur),
    '--mb-card-shadow': SHADOWS[card.shadow],
    '--mb-card-rule-left': card.rule === 'left' ? '4px' : '1px',
    '--mb-card-rule-top': card.rule === 'top' ? '4px' : '1px',
    '--mb-card-rule-left-color': card.rule === 'left' ? colors.accent : colors.rule,
    '--mb-card-rule-top-color': card.rule === 'top' ? colors.accent : colors.rule,
  };
  const declarations = (entries: Record<string, string>) =>
    Object.entries(entries)
      .map(([name, value]) => `${name}:${value}`)
      .join(';');
  // Layout numbers come from the same compiled frames the player uses for camera padding.
  const frame = (value: Compiled['layout']['desktop']) => ({
    '--mb-card-width': px(value.cardWidth),
    '--mb-gutter': px(value.gutter),
    '--mb-reserve': `${value.reserve.size}${value.reserve.unit}`,
  });
  const { layout } = compiled;
  return [
    `/* Generated by MapBard from the ${compiled.theme.preset} theme and ${layout.template} layout. */`,
    ...faces,
    `:root{${declarations({ ...vars, ...frame(layout.desktop) })}}`,
    `@media (max-width: ${layout.phoneMaxWidth}px){:root{${declarations(frame(layout.phone))}}}`,
    '',
  ].join('\n');
}

function html(compiled: Compiled): string {
  const scenes = compiled.scenes
    .map(
      (scene) =>
        // A scene is `scrollLength` + 1 viewports tall: its card rests for `scrollLength`, then transits.
        `<section class="scene" data-scene-id="${escapeHtml(scene.id)}" style="--mb-scroll-length: ${scene.motion.scrollLength}"><div class="scene-sticky"><div class="scene-card"><h2>${escapeHtml(scene.title)}</h2><div class="scene-narration">${scene.narration
          .split(/\n\s*\n/)
          .map((paragraph) => `<p>${escapeHtml(paragraph)}</p>`)
          .join('')}</div></div></div></section>`,
    )
    .join('\n');
  const credits = compiled.resources
    .filter((resource) => resource.credit || resource.qualification)
    .map(
      (resource) =>
        `<li>${escapeHtml(resource.name ?? resource.id)}: ${escapeHtml(resource.credit ?? '')}${resource.qualification ? ` — ${escapeHtml(resource.qualification)}` : ''}</li>`,
    )
    .join('');
  return `<!doctype html>
<html lang="en" data-mb-theme="${compiled.theme.preset}" data-mb-layout="${compiled.layout.template}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(compiled.title)}</title><link rel="stylesheet" href="vendor/maplibre-gl.css"><link rel="stylesheet" href="style.css"><link rel="stylesheet" href="theme.css"></head>
<body><div id="map" aria-label="Story map"></div><div id="mb-rail" class="mb-rail"><aside id="legends" class="mb-legend-host" hidden></aside><aside id="controls" class="mb-controls" hidden></aside><aside id="media" class="mb-compiled-media"></aside></div><button id="mb-motion-toggle" class="mb-motion-toggle" type="button" aria-pressed="false" hidden>Pause animation</button>
<main id="story"><header class="mb-intro"><div class="mb-intro-panel"><h1>${escapeHtml(compiled.title)}</h1><p>${escapeHtml(compiled.intent)}</p><p class="mb-scroll-hint">Scroll to explore the story</p></div></header>
${scenes}<footer class="mb-outro"><div class="mb-intro-panel"><p>Made with MapBard.</p>${credits ? `<h2>Sources and qualifications</h2><ul>${credits}</ul>` : ''}</div></footer></main>
<script src="vendor/maplibre-gl.js"></script><script src="compiled-data.js"></script><script src="player.js"></script><script src="compiled-app.js"></script></body></html>\n`;
}

const app = `(() => {
  'use strict';
  const payload = window.MAPBARD_COMPILED;
  const api = window.MapBardCompiledPlayer;
  const scenes = [...document.querySelectorAll('[data-scene-id]')];
  const root = document.documentElement;
  root.dataset.mbState = 'loading';
  const showError = (error) => {
    root.dataset.mbState = 'error';
    const panel = document.createElement('p');
    panel.setAttribute('role', 'alert');
    panel.textContent = 'Story playback failed: ' + String(error);
    document.querySelector('#story').prepend(panel);
  };
  try {
    if (!payload || !api || !window.maplibregl || !scenes.length) throw new Error('Required player or story data is missing');
    const first = payload.story.scenes[0];
    const base = payload.story.basemap;
    const styles = typeof base === 'object' && base.provider !== 'none' ? base.styles : [];
    let styleIndex = 0;
    let ready = false;
    let switching = false;
    let cleanup;
    let attribution;
    let timer;
    const notice = (message) => {
      let panel = document.querySelector('#mb-basemap-notice');
      if (!panel) { panel = document.createElement('p'); panel.id = 'mb-basemap-notice'; panel.setAttribute('role', 'status'); document.querySelector('#mb-rail').prepend(panel); }
      panel.textContent = message;
    };
    // Without an online style the map shows the theme's land colour, not a blank canvas.
    const emptyStyle = { version: 8, sources: {}, layers: [{ id: 'mb-background', type: 'background', paint: { 'background-color': payload.story.theme.colors.land } }] };
    maplibregl.setWorkerUrl('vendor/maplibre-gl-worker.js');
    const map = new maplibregl.Map({
      container: 'map', style: styles[0] ? styles[0].url : emptyStyle,
      center: first.camera.center, zoom: first.camera.zoom, attributionControl: false, maxPitch: 85,
    });
    map.scrollZoom.disable();
    // Map furniture follows the live camera: an auto scale bar, and a north arrow while rotated.
    map.addControl(new maplibregl.ScaleControl({ unit: 'metric', maxWidth: 110 }), 'bottom-left');
    map.addControl(new maplibregl.ScaleControl({ unit: 'imperial', maxWidth: 110 }), 'bottom-left');
    const north = document.createElement('div');
    north.className = 'maplibregl-ctrl mb-north';
    north.hidden = true;
    map.addControl({ onAdd: () => north, onRemove: () => north.remove() }, 'bottom-left');
    const failStyle = () => {
      if (switching || styleIndex >= styles.length) return;
      switching = true;
      clearTimeout(timer);
      if (cleanup) { cleanup(); cleanup = undefined; }
      root.dataset.mbState = 'loading';
      if (attribution) { map.removeControl(attribution); attribution = undefined; }
      ready = false;
      styleIndex++;
      if (styles[styleIndex]) { map.setStyle(styles[styleIndex].url); timer = setTimeout(failStyle, 12000); }
      else { notice('Online basemap unavailable; showing local story layers.'); map.setStyle(emptyStyle); }
    };
    if (styles.length) timer = setTimeout(failStyle, 12000);
    map.on('style.load', () => {
      try {
        clearTimeout(timer);
        ready = true;
        const chosen = styles[styleIndex];
        const credit = document.createElement('span');
        credit.textContent = chosen ? chosen.attribution : '';
        attribution = new maplibregl.AttributionControl({ customAttribution: credit.innerHTML });
        map.addControl(attribution);
        // Labels, theme tint, terrain, hillshade, sky and projection; online parts only with a provider style.
        api.styleBasemap(map, base, Boolean(chosen));
        // Keep the camera target clear of the layout's card and the rail of panels.
        const rail = document.querySelector('#mb-rail');
        // Attribution and scale bars only: the north arrow and pause button come and go mid-flight.
        const bottomControls = () => {
          const boxes = [...document.querySelectorAll('#map .maplibregl-ctrl-attrib, #map .maplibregl-ctrl-scale')]
            .map((element) => element.getBoundingClientRect())
            .filter((box) => box.width > 0 && box.height > 0);
          if (!boxes.length) return undefined;
          return {
            left: Math.min(...boxes.map((box) => box.left)), top: Math.min(...boxes.map((box) => box.top)),
            right: Math.max(...boxes.map((box) => box.right)), bottom: Math.max(...boxes.map((box) => box.bottom)),
          };
        };
        const frame = () => {
          const viewport = { width: innerWidth, height: innerHeight };
          const padding = api.cameraPadding(payload.story.layout, viewport, rail.getBoundingClientRect(), bottomControls());
          return { padding, zoomOffset: api.zoomOffset(payload.story.layout, viewport, padding) };
        };
        // Callout labels keep clear of the card area, the rail and the map controls.
        const obstacles = () => [
          api.reservedArea(payload.story.layout, { width: innerWidth, height: innerHeight }),
          ...[rail, ...document.querySelectorAll('#map .maplibregl-ctrl, #mb-motion-toggle')]
            .map((element) => element.getBoundingClientRect())
            .filter((box) => box.width > 0 && box.height > 0),
        ];
        const adapter = api.createMapLibreAdapter(payload.story, payload.data, map, maplibregl, { frame, obstacles });
        const view = api.createDomView({ scenes, media: document.querySelector('#media'), controls: document.querySelector('#controls'), legends: document.querySelector('#legends') });
        // Looping motion always gets a visible pause control (WCAG 2.2.2).
        const toggle = document.querySelector('#mb-motion-toggle');
        const onMotionChange = (status) => {
          toggle.hidden = !status.loop;
          toggle.setAttribute('aria-pressed', String(status.paused));
          toggle.textContent = status.paused ? 'Play animation' : 'Pause animation';
        };
        const player = api.createPlayer(payload.story, adapter, view, { reducedMotion: () => matchMedia('(prefers-reduced-motion: reduce)').matches, onMotionChange });
        const onToggle = () => player.setPaused(!player.isPaused());
        toggle.addEventListener('click', onToggle);
        player.enter(first.id);
        const tracker = api.trackScenes(player, scenes, payload.story.scenes);
        const stopNorth = api.createNorthArrow(north, adapter);
        // Readiness hook for visual QA and the workbench; reading it never changes playback.
        const story = {
          sceneIds: payload.story.scenes.map((scene) => scene.id),
          activeSceneId: () => player.activeSceneId(),
          progress: () => player.progress(),
          paused: () => player.isPaused(),
          whenIdle: () => new Promise((resolve) => { map.once('idle', () => resolve()); map.triggerRepaint(); }),
        };
        // Capture pages opt in before load; only they may hold a scene at a chosen progress.
        if (window.MAPBARD_CAPTURE === true) {
          story.seek = (sceneId, p) => { tracker.pin(sceneId, p); player.seek(sceneId, p); };
          story.release = () => tracker.release();
        }
        window.MapBardStory = Object.freeze(story);
        const refit = () => adapter.refit();
        addEventListener('resize', refit);
        // The title and credits panels own the screen: hide the rail while either crosses its middle.
        const framing = new Set();
        const bookends = new IntersectionObserver((entries) => {
          for (const entry of entries) entry.isIntersecting ? framing.add(entry.target) : framing.delete(entry.target);
          root.toggleAttribute('data-mb-bookend', framing.size > 0);
        }, { rootMargin: '-50% 0px -50% 0px' });
        document.querySelectorAll('.mb-intro, .mb-outro').forEach((element) => bookends.observe(element));
        cleanup = () => { tracker.dispose(); stopNorth(); toggle.removeEventListener('click', onToggle); toggle.hidden = true; bookends.disconnect(); removeEventListener('resize', refit); player.dispose(); delete window.MapBardStory; };
        switching = false;
        root.dataset.mbState = 'ready';
      } catch (error) { showError(error); map.remove(); }
    });
    map.on('error', (event) => { if (styles.length && styleIndex < styles.length) failStyle(); else if (ready) console.error(event.error || 'Map error'); });
    addEventListener('pagehide', () => { clearTimeout(timer); if (cleanup) cleanup(); map.remove(); }, { once: true });
  } catch (error) { showError(error); }
})();\n`;

/** Pure publication generation. The caller supplies a fresh input snapshot and exact data bytes. */
export function renderCompiled(
  compiled: Compiled,
  publication: PublicationInputs,
  options: RenderCompiledOptions = {},
): Result<CompiledBundle> {
  if (
    !CompiledSchema.safeParse(compiled).success ||
    !PublicationInputsSchema.safeParse(publication).success ||
    !RenderCompiledOptionsSchema.safeParse(options).success
  ) {
    return {
      ok: false,
      diagnostics: [
        issue(
          'VALUE_INVALID',
          [],
          'Publication inputs do not match the compiled contract.',
          'Recompile and provide validated publication inputs.',
        ),
      ],
    };
  }
  const diagnostics: Diagnostic[] = [];
  if (JSON.stringify(publication.currentInput) !== JSON.stringify(compiled.input))
    diagnostics.push(
      issue(
        'INPUT_STALE',
        ['currentInput'],
        'Authored project input differs from this compilation.',
        'Reload and recompile the current project.',
      ),
    );
  const expected = new Map(compiled.input.resources.map((item) => [item.id, item.sha256]));
  const dataResources = compiled.resources.filter((item) => item.kind === 'data');
  const data = new Map<string, unknown>();
  if (
    publication.dataBytes.length !== dataResources.length ||
    new Set(publication.dataBytes.map((item) => item.id)).size !== publication.dataBytes.length
  )
    diagnostics.push(
      issue(
        'INPUT_STALE',
        ['dataBytes'],
        'Data byte membership differs from compiled resources.',
        'Reload and recompile the current data.',
      ),
    );
  for (const resource of dataResources) {
    const item = publication.dataBytes.find((entry) => entry.id === resource.id);
    if (!item || sha256(item.bytes) !== expected.get(resource.id)) {
      diagnostics.push(
        issue(
          'INPUT_STALE',
          ['dataBytes'],
          'Data bytes differ from the compilation.',
          'Reload and recompile this source.',
          { sourceId: resource.id },
        ),
      );
      continue;
    }
    try {
      const value: unknown = JSON.parse(
        new TextDecoder('utf-8', { fatal: true }).decode(item.bytes),
      );
      if (
        !value ||
        typeof value !== 'object' ||
        !('type' in value) ||
        value.type !== 'FeatureCollection' ||
        !('features' in value) ||
        !Array.isArray(value.features)
      )
        throw new Error('Not GeoJSON');
      data.set(resource.id, value);
    } catch {
      diagnostics.push(
        issue(
          'VALUE_INVALID',
          ['dataBytes'],
          'Compiled source is not a GeoJSON FeatureCollection.',
          'Supply valid GeoJSON bytes and recompile.',
          { sourceId: resource.id },
        ),
      );
    }
  }
  const localMedia = compiled.resources.filter((item) => item.kind !== 'data' && item.bundlePath);
  if (
    publication.assets.length !== localMedia.length ||
    new Set(publication.assets.map((item) => item.id)).size !== publication.assets.length
  )
    diagnostics.push(
      issue(
        'RESOURCE_MISSING',
        ['assets'],
        'Local asset membership differs from compiled resources.',
        'Reload the project assets.',
      ),
    );
  for (const resource of compiled.resources) {
    const path = resource.bundlePath;
    if (path && !safePath(path))
      diagnostics.push(
        issue(
          'ASSET_PATH_INVALID',
          ['resources'],
          'Compiled bundle path is unsafe.',
          'Use a project-relative path without traversal.',
          { assetId: resource.id },
        ),
      );
    if (resource.kind !== 'data' && Boolean(path) === Boolean(resource.remoteUrl))
      diagnostics.push(
        issue(
          'VALUE_INVALID',
          ['resources'],
          'Media must have exactly one local or remote location.',
          'Recompile this media resource.',
          { assetId: resource.id },
        ),
      );
    if (
      resource.posterId &&
      !compiled.resources.some((item) => item.id === resource.posterId && item.kind === 'image')
    )
      diagnostics.push(
        issue(
          'REFERENCE_MISSING',
          ['resources'],
          'Video poster does not refer to an image resource.',
          'Register the poster image and recompile.',
          { assetId: resource.id },
        ),
      );
  }
  for (const resource of localMedia) {
    const asset = publication.assets.find((item) => item.id === resource.id);
    if (
      !asset ||
      asset.bundlePath !== resource.bundlePath ||
      asset.sha256 !== expected.get(resource.id)
    )
      diagnostics.push(
        issue(
          'INPUT_STALE',
          ['assets'],
          'Local media declaration differs from the compilation.',
          'Reload and recompile this asset.',
          { assetId: resource.id },
        ),
      );
  }
  const basemapNetwork =
    typeof compiled.basemap === 'object' && compiled.basemap.provider !== 'none'
      ? [
          ...compiled.basemap.styles.map((style) => style.url),
          ...(compiled.basemap.terrain ? [compiled.basemap.terrain.tiles] : []),
        ]
      : [];
  const expectedNetwork = [
    ...new Set([
      ...compiled.resources.flatMap((resource) => (resource.remoteUrl ? [resource.remoteUrl] : [])),
      ...basemapNetwork,
    ]),
  ].sort();
  if (
    JSON.stringify(expectedNetwork) !== JSON.stringify(compiled.requiredNetwork) ||
    expectedNetwork.some((url) => !/^https?:\/\//i.test(url))
  )
    diagnostics.push(
      issue(
        'VALUE_INVALID',
        ['requiredNetwork'],
        'Remote dependencies are not declared consistently.',
        'Recompile with explicit HTTP(S) media dependencies.',
      ),
    );
  if (diagnostics.length) return { ok: false, diagnostics };
  const payload = Object.fromEntries(data);
  const files = {
    'index.html': html(compiled),
    'compiled-data.js': `window.MAPBARD_COMPILED = ${safeJson({ story: compiled, data: payload })};\n`,
    'compiled-app.js': app,
    'theme.css': themeCss(compiled),
  };
  return {
    ok: true,
    value: {
      files,
      mediaCopies: publication.assets,
      fonts: bundledFonts(compiled),
      input: compiled.input,
      diagnostics: [],
      requiredNetwork: compiled.requiredNetwork,
    },
    diagnostics: [],
  };
}
